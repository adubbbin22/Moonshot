/** Shorthand for the common "thesis wrong / partly right / moonshot" shape. */
function powerLaw(
  wrong: [number, number],
  partly: [number, number],
  moonshot: [number, number],
): Scenario[] {
  return [
    { label: 'Thesis wrong', probability: wrong[0], multiple: wrong[1] },
    { label: 'Partly right', probability: partly[0], multiple: partly[1] },
    { label: 'Moonshot', probability: moonshot[0], multiple: moonshot[1] },
  ];
}

